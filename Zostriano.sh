📜 ZOSTRIANO — Texto Completo
 
PARTE 1: La Llamada
 
Yo, Zostriano, estaba en la montaña solo, y me dije a mí mismo: "Si quiero conocer la verdad, debo buscarla en mí mismo." Me senté y oré profundamente.
 
De pronto apareció ante mí un ángel de Luz. Me dijo:
 
"Zostriano, ¿por qué te entregas a la muerte? Tú eres hijo de la Luz. Ven, te mostraré el camino de regreso."
 
Me dijo que este mundo es una sombra, una imagen engañosa. Quien busca la verdad debe trascenderlo todo.
 
 
 
PARTE 2: El Ascenso
 
El ángel me llevó en una nube luminosa. Dejé mi cuerpo aquí abajo, guardado por glorias. Atravesé todo el mundo y los cielos que lo rodean.
 
Pasé por los poderes que crearon este mundo. Ellos me preguntaron: "¿Quién eres tú que pasas por nosotros?" Yo no les respondí, porque no eran de mi origen.
 
 
 
PARTE 3: Los Siete Cielos y los Poderes
 
Llegué a los siete cielos. Cada uno tiene su propio poder:
 
- Los primeros crearon la materia
​
- Los siguientes crearon las almas
​
- El último, Yaldabaoth, se cree el único Dios
 
Todos dijeron: "Nosotros somos los dueños de todo." Pero yo vi que solo eran sombras de lo verdadero.
 
 
 
PARTE 4: Las Regiones Superiores
 
Seguí subiendo. Llegué a regiones donde no hay materia, ni cuerpo, ni forma. Allí vi seres que no hablan, sino que se conocen solo con el pensamiento.
 
Me explicaron que todo lo que existe aquí abajo fue creado por error. Una fuerza llamada Sofía quiso crear algo por su cuenta y nació este mundo imperfecto.
 
 
 
PARTE 5: El Origen del Alma
 
Las almas que están aquí abajo vinieron de lo alto. Se olvidaron de quiénes son por el peso del cuerpo y el olvido.
 
Algunas despiertan y recuerdan su origen. Otras permanecen dormidas y vuelven a caer en la prisión una y otra vez.
 
 
 
PARTE 6: Las Puertas de Luz
 
Subí aún más y llegué a las Cuatro Luces verdaderas:
 
- Armozel — Bondad
​
- Oroiael — Providencia
​
- Daveithai — Divinidad
​
- Eleleth — Comprensión
 
Cada una me enseñó una verdad. Me bautizaron con el bautismo de Luz, que no es agua sino conocimiento.
 
 
 
PARTE 7: El Espíritu Invisible
 
Finalmente llegué al Espíritu Invisible, que no tiene forma ni nombre. No se puede describir, solo se puede conocer en silencio.
 
Allí escuché:
 
"Tú eres uno con nosotros. Has regresado de donde viniste."
 
Comprendí que yo no soy el cuerpo, ni el alma, sino una chispa de esa Luz eterna.
 
 
 
PARTE 8: El Regreso y la Enseñanza
 
Regresé a este mundo no porque me obligaran, sino para decirles a otros el camino:
 
"Despertad. Recordad quiénes sois. No pertenecéis aquí. Sois hijos de la Luz. El camino de regreso no está fuera de vosotros, sino dentro."
 
"Quien se conoce a sí mismo conoce el todo. Quien recuerda su origen regresa a casa."
 
 
 
PARTE 9: El Destino
 
- Los que despiertan: atraviesan todas las puertas y regresan a la Luz para siempre
​
- Los que no despiertan: vuelven a nacer en este mundo o en otros inferiores, hasta que despierten
​
- Los que se aferran a este mundo: permanecen en la oscuridad, olvidados
 
"Este mundo pasará. Solo la Luz permanece. Bienaventurado el que ha despertado antes de morir."